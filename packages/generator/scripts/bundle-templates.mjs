// Bundle the repository's templates/ into a JS module so the generator has no
// filesystem dependency at runtime (and works in the browser). This is the
// single source of truth: the same templates/*.sh and templates/licenses/*.txt
// consumed by the bash `zap-sh` oracle. Run at build time (prebuild).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const templatesDir = join(repoRoot, 'templates');
const licensesDir = join(templatesDir, 'licenses');
const outFile = join(here, '..', 'src', 'templates.generated.js');

// templates/*.sh -> { "<basename without .sh>": "<contents>" }
const templates = {};
for (const file of readdirSync(templatesDir).sort()) {
  if (!file.endsWith('.sh')) continue;
  templates[basename(file, '.sh')] = readFileSync(join(templatesDir, file), 'utf8');
}

// templates/licenses/*.txt -> { "<basename without .txt, original case>": "<contents>" }
const licenses = {};
for (const file of readdirSync(licensesDir).sort()) {
  if (!file.endsWith('.txt')) continue;
  licenses[basename(file, '.txt')] = readFileSync(join(licensesDir, file), 'utf8');
}

const banner =
  '// AUTO-GENERATED by scripts/bundle-templates.mjs — do not edit.\n' +
  '// Source of truth: <repo>/templates/. Regenerated on every build.\n';

const body =
  banner +
  'export const TEMPLATES = ' + JSON.stringify(templates, null, 2) + ';\n' +
  'export const LICENSES = ' + JSON.stringify(licenses, null, 2) + ';\n';

writeFileSync(outFile, body);

const tNames = Object.keys(templates).join(', ');
const lNames = Object.keys(licenses).join(', ');
console.log(`bundled templates: [${tNames}]  licenses: [${lNames}] -> src/templates.generated.js`);
